    def _ip_to_int(self, ip: str) -> int:
        """
        将IP地址转换为整数
        
        :param ip: IP地址字符串
        :return: IP整数
        """
        try:
            return int(ipaddress.ip_address(ip))
        except ValueError as e:
            logger.error(f"IP地址格式错误: {ip}")
            raise
    
    def _is_ip_in_range(self, ip: str, start_ip: str, end_ip: str) -> bool:
        """
        检查IP是否在指定范围内
        
        :param ip: 待检查的IP
        :param start_ip: 范围起始IP
        :param end_ip: 范围结束IP
        :return: 是否在范围内
        """
        try:
            ip_int = self._ip_to_int(ip)
            start_int = self._ip_to_int(start_ip)
            end_int = self._ip_to_int(end_ip)
            return start_int <= ip_int <= end_int
        except Exception as e:
            logger.error(f"检查IP范围失败: {e}")
            return False
    
    def recognize_region(self, ip: str) -> str:
        """
        识别IP地址的地域
        
        :param ip: IP地址
        :return: 地域分类（REGION_CHINA/REGION_US_EU/REGION_OTHER/REGION_FAILED）
        """
        if not ip or ip == "未知":
            logger.error(f"IP地址无效: {ip}")
            return REGION_FAILED
        
        try:
            # 验证IP格式
            socket.inet_aton(ip)
            
            # 检查是否在中国IP段
            for start_ip, end_ip in self.china_ip_ranges:
                if self._is_ip_in_range(ip, start_ip, end_ip):
                    logger.info(f"IP {ip} 识别为: {REGION_CHINA}")
                    return REGION_CHINA
            
            # 检查是否在美国/欧洲IP段
            for start_ip, end_ip in self.us_eu_ip_ranges:
                if self._is_ip_in_range(ip, start_ip, end_ip):
                    logger.info(f"IP {ip} 识别为: {REGION_US_EU}")
                    return REGION_US_EU
            
            # 其他地域
            logger.info(f"IP {ip} 识别为: {REGION_OTHER}")
            return REGION_OTHER
            
        except socket.error:
            logger.error(f"IP地址格式无效: {ip}")
            return REGION_FAILED
        except Exception as e:
            logger.error(f"IP识别失败: {ip}, 错误: {e}")
            return REGION_FAILED


